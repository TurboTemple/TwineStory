// media.mjs — find every media file under assets/media and build the
// manifest the game uses to look them up by name.
//
//   assets/media/location/red_lion.webp        → key "location/red_lion"
//   assets/media/npc/dr_okafor.jpg              → key "npc/dr_okafor"
//   assets/media/bodyPart/hair_colour/pink.png  → key "bodyPart/hair_colour/pink"
//
// If the same key has several files, the first extension in PRIORITY wins.

import fs from "node:fs";
import path from "node:path";

export const MEDIA_DIR = "assets/media";
export const PRIORITY = [".mp4", ".webm", ".gif", ".webp", ".avif", ".png", ".jpg", ".jpeg", ".svg"];
export const VIDEO = new Set([".mp4", ".webm"]);

/**
 * Scan a repository's assets/media folder.
 * @param {string} root  Repository root.
 * @returns {Record<string, string>} key → relative URL (e.g. "assets/media/npc/x.webp")
 */
export function buildManifest(root) {
	const base = path.join(root, MEDIA_DIR);
	const found = {};
	if (!fs.existsSync(base)) return found;
	const walk = (dir) => {
		for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
			const p = path.join(dir, entry.name);
			if (entry.isDirectory()) {
				walk(p);
				continue;
			}
			const ext = path.extname(entry.name).toLowerCase();
			if (!PRIORITY.includes(ext)) continue;
			const rel = path.relative(base, p).split(path.sep).join("/");
			const key = rel.slice(0, -ext.length);
			const url = `${MEDIA_DIR}/${rel}`;
			const cur = found[key];
			if (!cur || PRIORITY.indexOf(ext) < PRIORITY.indexOf(path.extname(cur).toLowerCase())) found[key] = url;
		}
	};
	walk(base);
	return Object.fromEntries(Object.entries(found).sort(([a], [b]) => a.localeCompare(b)));
}

/**
 * Every passage still holding a "[… edit here]" placeholder, and the file
 * it's in, for the debug Writing checklist.
 * @param {string} root  Repository root.
 * @param {(text: string, file: string) => {name: string, text: string}[]} parseTwee
 * @returns {Record<string, string>} passage name → file (relative to the repository)
 */
export function findPlaceholders(root, parseTwee) {
	const out = {};
	const walk = (dir) => {
		for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
			const p = path.join(dir, entry.name);
			if (entry.isDirectory()) walk(p);
			else if (entry.name.endsWith(".twee")) {
				const rel = path.relative(root, p).split(path.sep).join("/");
				for (const ps of parseTwee(fs.readFileSync(p, "utf8"), rel)) if (/\[[^\]\n]* edit here\]/.test(ps.text)) out[ps.name] = rel;
			}
		}
	};
	walk(path.join(root, "src"));
	return Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)));
}

/**
 * The picture credits: assets/media/credits.json, { "location/red_lion.webp": { title,
 * creator, creator_url, license, license_version, license_url, foreign_landing_url, source } }.
 * Entries for files that no longer exist are dropped.
 */
export function readCredits(root) {
	const file = path.join(root, MEDIA_DIR, "credits.json");
	if (!fs.existsSync(file)) return {};
	const all = JSON.parse(fs.readFileSync(file, "utf8"));
	return Object.fromEntries(Object.entries(all).filter(([f]) => fs.existsSync(path.join(root, MEDIA_DIR, f))));
}

/** The Story JavaScript file that carries the manifest (and the placeholder list) into the game. */
export function manifestScript(manifest, placeholders = {}, sources = {}, credits = {}) {
	const json = (v) => JSON.stringify(v, null, "\t").replace(/\n/g, "\n\t");
	return `/* GENERATED by scripts/media-manifest.mjs at build time — do not edit or commit. */
(function () {
	"use strict";
	setup.__mediaManifest = ${json(manifest)};
	// Passages still saying "[… edit here]", and their files (debug Writing checklist).
	setup.__placeholders = ${json(placeholders)};
	// Which file defines each piece of content: file → ["type:id"] (debug Tuning page).
	setup.__sources = ${JSON.stringify(sources)};
	// Where each picture came from and its licence (assets/media/credits.json; Menu → Credits).
	setup.__mediaCredits = ${JSON.stringify(credits)};
})();
`;
}
